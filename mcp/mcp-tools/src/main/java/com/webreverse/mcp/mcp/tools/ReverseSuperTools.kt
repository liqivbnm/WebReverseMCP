    // ---------------- 序列化辅助 ----------------

    private fun traceEventJson(e: TraceEvent) = buildJsonObject {
        put("seq", e.seq)
        put("ts", e.ts)
        put("source", e.source.name)
        put("kind", e.kind.name)
        put("name", e.name)
        if (e.asyncChainId.isNotBlank()) put("chainId", e.asyncChainId)
        if (e.parentEventId >= 0) put("parentSeq", e.parentEventId)
        if (e.output != null) put("output", e.output!!.raw)
        if (e.input != null) put("input", e.input!!.raw)
        if (e.error.isNotBlank()) put("error", e.error)
        val fps = e.values.mapNotNull { if (it.hasFingerprint) it.fingerprint else null }
        if (fps.isNotEmpty()) put("fingerprints", JsonArray(fps.map { JsonPrimitive(it) }))
    }

    private fun bufferStatsJson(buf: TraceEventBuffer) = buildJsonObject {
        put("size", buf.stats().size)
        put("lastSeq", buf.stats().lastSeq)
        put("distinctFingerprints", buf.stats().distinctFingerprints)
        put("distinctChains", buf.stats().distinctChains)
        put("bySource", buildJsonObject { buf.stats().bySource.forEach { (k, v) -> put(k, JsonPrimitive(v)) } })
    }
